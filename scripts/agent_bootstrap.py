"""Run by the SETUP AGENT on the user's persistent runtime, never by the user.

Connected tools provision the cloud project/runtime/HTTPS first. This script
installs Python dependencies when requested, verifies local prerequisites and
returns a short-lived onboarding link. It does not invent hosting permissions.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def execute(args):
    if args.action == "plan":
        from vso.bootstrap import plan
        return plan(json.loads(Path(args.capabilities).read_text()))
    if os.getenv("VSO_RUNTIME_PERSISTENT") != "1":
        raise ValueError("Setup must run on a connected persistent runtime, never the chat scratch environment")
    if os.getenv("VSO_CLOUD_MANAGED") != "1":
        raise ValueError("Provision a managed cloud app service; local PCs and user-managed VPSs are excluded")
    origin = os.getenv("VSO_PUBLIC_URL", "").rstrip("/")
    from urllib.parse import urlsplit
    p = urlsplit(origin)
    if p.scheme != "https" or not p.hostname or p.path or p.query or p.fragment or p.username:
        raise ValueError("The agent must provision a clean HTTPS origin and inject VSO_PUBLIC_URL")
    data_dir = Path(os.getenv("VSO_DATA_DIR", "")).expanduser()
    if not os.getenv("VSO_DATA_DIR") or not data_dir.is_absolute() or ROOT == data_dir.resolve() or ROOT in data_dir.resolve().parents:
        raise ValueError("The agent must mount a private persistent data directory outside the source checkout")
    if args.install_dependencies:
        subprocess.run([sys.executable, "-m", "pip", "install", "-r", str(ROOT / "requirements.txt")], check=True, stdout=sys.stderr)
    if not shutil.which("node"): raise ValueError("The provisioned runtime needs Node.js 22+")
    version = subprocess.check_output(["node", "--version"], text=True).strip()
    if int(version.removeprefix("v").split(".")[0]) < 22: raise ValueError("Node.js 22+ is required")
    if os.getenv("VSO_REMOTE_BROWSER") != "1": raise ValueError("Agent-first hosted onboarding requires the remote-browser runtime")
    for binary in ("Xvfb", "x11vnc", "websockify"):
        if not shutil.which(binary): raise ValueError("The agent must provision " + binary)
    chrome = os.getenv("VSO_CHROME")
    if not chrome or not Path(chrome).is_file(): raise ValueError("The agent must configure the actual Chrome executable")
    if os.getenv("VSO_STATE_BACKEND") != "supabase": raise ValueError("Agent-first deployments require the supplied Supabase state adapter")
    # IDs are generated by the agent, injected as runtime secrets/config, not entered by the user.
    uuid.UUID(os.environ.get("VSO_INSTALLATION_ID", ""))
    from vso.supabase_store import from_environment
    from vso.engine import Engine
    store = from_environment(data_dir)
    engine = Engine(store, origin)
    store.put("setup", "bootstrap", {"version": "0.2.0", "status": "runtime_prepared", "agent_owned": True})
    ticket = store.ticket("pair", {}, ttl=600)
    result = {"status": "runtime_prepared", "onboarding_url": origin + "/pair?ticket=" + ticket,
              "dashboard_url": origin + "/dashboard", "mcp_url": origin + "/mcp",
              "user_commands_required": False, "onboarding_expires_in": 600,
              "agent_next": ["Verify live HTTPS health and browser startup", "Package/create the single remote plugin",
                             "Present plugin install/consent UI", "Verify a harmless plugin call", "Give the user the onboarding link"],
              "native_images": "Host-native only; asset transfer must be verified separately"}
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("plan", "prepare"))
    parser.add_argument("--capabilities")
    parser.add_argument("--install-dependencies", action="store_true")
    args = parser.parse_args()
    try: print(json.dumps(execute(args), indent=2))
    except Exception as e:
        print(json.dumps({"status": "blocked", "error": str(e), "user_commands_required": False}), file=sys.stderr)
        sys.exit(1)
